print("Ethics Case Study Chatbot")
print("Case: You found a lost wallet in college.")
print("\nWhat will you do?")
print("1. Keep the money")
print("2. Give it to the college office")
print("3. Ignore it")
choice = input("Enter your choice (1/2/3): ")
if choice == "1":
    print("Feedback: Keeping the money is unethical.")
    print("It violates honesty and the owner's rights.")
elif choice == "2":
    print("Feedback: This is an ethical choice.")
    print("It shows honesty and responsibility.")
elif choice == "3":
    print("Feedback: Ignoring the wallet may prevent")
    print("the owner from recovering their property.")
else:
    print("Invalid choice. Please select 1, 2 or 3.")
print("\nEthical principle: Honesty and responsibility")
